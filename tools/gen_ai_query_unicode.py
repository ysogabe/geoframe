#!/usr/bin/env python3
"""Generate Python Unicode full casefold for E6; no user data or network."""
import sys
import unicodedata
from pathlib import Path
path = Path(__file__).resolve().parents[1] / 'crates/geoframe/src/pycasefold.rs'
def literal(text):
    return '"' + ''.join('\\u{%x}' % ord(c) for c in text) + '"'
lines = ['//! Generated by tools/gen_ai_query_unicode.py, Unicode ' + unicodedata.unidata_version + '.',
         'pub(crate) fn fold(c: char) -> String {', '    match c {']
for i in range(sys.maxunicode + 1):
    c = chr(i)
    if c.casefold() != c:
        lines.append("        '\\u{%x}' => %s.into()," % (i, literal(c.casefold())))
lines.extend(['        _ => c.to_string(),', '    }', '}', ''])
text = '\n'.join(lines)
if '--check' in sys.argv:
    assert path.read_text() == text, 'regenerate Unicode casefold'
else:
    path.write_text(text)
