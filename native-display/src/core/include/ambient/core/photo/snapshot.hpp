// ambient/core/photo/snapshot.hpp — 写真スケジューラの永続化
//
// 【この層の制約】docs/PORTABILITY.md と CMakeLists.txt 冒頭を必ず読むこと。
//
// ============================================================================
// ★容量の問題 ― Mac では通り Tab5 で破綻する典型
// ============================================================================
//
// `shown`（各写真の最終表示ラウンド）は**設計値2000件ぶんのエントリ**を持ちうる。
// "id:round" 形式で約 11〜14KB になる。
//
//   Mac のファイル : 収まる。何の問題も起きない。
//   Tab5 の NVS    : **入らない。** パーティションは 20KB しかなく、
//                    しかも hogo-meter が既に 4 つの namespace を使っている。
//
// この差は Mac 上のテストでは絶対に見えない。移植の段階で初めて分かり、
// そこで「エントリ数に上限を掛けられない構造だった」と判明すると詰む。
//
// ============================================================================
// ★このヘッダで凍結するのは「上限を後付けできること」であって、形式ではない
// ============================================================================
//
// 直列化形式そのもの（JSON か、独自のバイナリか、区切り文字か）は **未決定**である。
// それはレーン 1B が決める。ここで決めてしまうと、実測前に形式を固定することになる。
//
// ここで凍結するのは次の 2 点だけである。
//
//   1. shown / playQueue が **可変長のエントリ列** であること
//      （固定長配列やマップを型に露出させない。上限を掛けられなくなる）
//   2. 上限を表す SnapshotLimits と、それを適用する truncateForStore() が
//      **形式の決定より前に** 存在すること
//
// ============================================================================
// 上限を掛けるとき、何を捨てるか（1B が選ぶ選択肢）
// ============================================================================
//
// A. shown を LRU で切る（round が最も古いものから捨てる）
//    捨てられた写真は「未表示」= PRI_NEVER (45pt) 扱いに戻る。
//    → 飢餓は起きない（むしろ優先的に出る）が、全網羅の周期が伸びる。
//    → 実装が単純。既定候補。
//
// B. shown を「相対ラウンド」に圧縮する
//    roundNo との差を保存し、差が一定を超えたら捨てる。
//    → A と実質同じだが、round の絶対値が増え続ける問題も同時に解ける。
//
// C. shown を持たず、playQueue と roundNo だけ保存する
//    → 保存量は劇的に減るが、再起動のたびに表示履歴が失われる。
//      「一度も表示していない」判定ができなくなり、全網羅が壊れる。
//    → 推奨しない。
//
// D. ID を短縮する（ハッシュへ写す）
//    → 衝突すると別の写真を「表示済み」と誤認する。設計値2000件なら32bitで
//      衝突確率は低いが、ゼロではない。誤認しても致命的でない
//      （1 枚が出にくくなるだけ）ので、A と組み合わせる価値はある。
//
// ★どれを選ぶにせよ、決めたら docs/CORE_CONTRACTS.md に記録すること。
//
// ############################################################################
// # ★1B の決定（2026-07。ここが「決めていないこと」からの移動先）
// ############################################################################
//
// ---- 決定 1: 直列化形式 = 長さ前置きの行指向テキスト -----------------------
//
// 具体形は encodeSnapshot() の実装冒頭に BNF で書いてある。要点だけ:
//
//   * 先頭に "gfp<version>" のマジック。★未知バージョンは decode が nullopt。
//   * 文字列（ID・シグネチャ）は **必ず "<バイト長>:" を前置きする**。
//     ID は認証の無い LAN 上のサーバ由来なので、区切り文字（改行・コロン）が
//     混ざりうる前提で扱う。長さ前置きなら中身が何であっても曖昧にならず、
//     エスケープ処理（= 実装ミスの温床）が要らない。
//   * 数値は 10 進 ASCII。バイナリにしないのは、エンディアンと
//     アラインメントを Mac / ESP32-P4 で気にしたくないため。
//     どちらもリトルエンディアンだが、それに依存する理由が無い。
//   * 1 エントリ ≈ 10 バイト（"4:1001:27\n"）。この見積もりが下の上限値の根拠。
//
// JSON にしなかった理由: Core に JSON パーサを持ち込まないため
// （依存を増やさない規律。自前で書けば結局この形式と同じ手間になる）。
//
// ---- 決定 2: 捨てる規則 = 選択肢 A（round が古い順） -----------------------
//
// truncateForStore() は round の昇順（古い順）に shown を捨てる。
// 捨てられた写真は「未表示」= PRI_NEVER (45pt) に戻る。
//
// ---- 決定 3: 上限値と、★上限を超えたときに何が壊れるか --------------------
//
// ★「全網羅がちょうど 1 巡で終わる」性質を保つには、shown は
//   **1巡ぶんの全写真**を覚えている必要がある。つまり必要件数は
//
//       maxShownEntries >= 写真総数 N
//
//   であり、**「TRIP_MAXとの関係でNより小さくできる」ことは無い**。
//
// ★上限を N 未満にすると何が壊れるか（劣化の中身。壊れ方は 1 つだけ）:
//
//   飢餓は起きない。捨てられた写真は PRI_NEVER に戻るので、むしろ
//   選ばれやすくなる方向へ倒れる。壊れるのは **全網羅の周期** である。
//   「未表示」と「表示したが忘れた」を区別できなくなるため、選出が
//   クーポンコレクタ的になり、最大トリップ 168 枚では
//   28 ラウンド → 概算 (168/TRIP_MAX)·H(168) ≈ 160 ラウンド、
//   すなわち **約 5.7 倍** に伸びる（H は調和数。上界の見積もりであって実測ではない）。
//   1 ラウンド ≈ 159 枚 x 約 17 秒 ≈ 45 分なので、約 21 時間 → 約 5 日。
//
//   ★つまり「表示されない写真が出る」のではなく「一周に何日かかるか」が
//     変わる。この差は Mac 上のテストでは体感できないので、数値で残す。
//
// ★結論（Tab5 移植担当への申し送り）:
//   NVS 単独（パーティション 20KB、hogo-meter が 4 namespace 使用中）に
//   設計値2000件は入らない。**上限を掛ける機構だけでは解決しない。**
//   本命は選択肢 (b)、すなわち Tab5 では NVS ではない IStateStore を使うこと
//   （パーティション表末尾の約 3.9MB 未割当領域に LittleFS を切る余地がある）。
//   kTab5ProvisionalLimits は「LittleFS が使えなかった場合の縮退運転」であり、
//   そのとき上のとおり全網羅の周期が約 5.7 倍になることを承知して使うこと。

#pragma once

#include <cstddef>
#include <cstdint>
#include <optional>
#include <string>
#include <string_view>
#include <vector>

#include "ambient/core/model/photo.hpp"
#include "ambient/core/rng.hpp"

namespace ambient::core {

// 各写真の最終表示ラウンド。
struct ShownEntry {
  PhotoId photoId;
  std::uint32_t round{0};

  [[nodiscard]] bool operator==(const ShownEntry&) const noexcept = default;
};

// 直列化フォーマットのバージョン。
// ★形式を変えたら必ず上げること。上げないと、古い形式を新しいパーサが
//   読んで沈黙のうちに壊れたデータを使う。
inline constexpr std::uint32_t kSnapshotVersion = 1;

struct SchedulerSnapshot {
  std::uint32_t version{kSnapshotVersion};

  // 現在のラウンド番号。
  std::uint32_t roundNo{0};

  // 再生待ちの写真 ID（先頭が次に出る）。
  // ★添字ではなく ID で持つ。manifest 再取得で添字が動いても
  //   再生位置が巻き戻らないため（出典 scheduler.js の設計コメント）。
  std::vector<PhotoId> playQueue;

  // 最後に同期した manifest のシグネチャ。
  std::string photosSignature;

  // ★設計値2000件ぶんになりうる。ここが容量問題の本体。
  //
  // ★不変条件: photoId の昇順にソートされている。
  //   markShown / buildPlayOrder が 1 ラウンドに数千回引くので、
  //   線形探索だと O(N^2) になる。decodeSnapshot は復元時に必ずソートし直す
  //   （保存ファイルが手で編集されていても不変条件が壊れないようにするため）。
  std::vector<ShownEntry> shown;

  // ★乱数の状態。これを保存しないと再起動のたびに乱数列が
  //   最初からになり、「再起動をまたいだ再現性」が失われる。
  //   SchedulerRng のみ。TransitionRng は演出の見た目にしか効かないので
  //   保存しない（保存するなら別途決めること）。
  RngState schedulerRng{};

  // --------------------------------------------------------------------------
  // ここから下は ★永続化しない（encodeSnapshot は書かない / decodeSnapshot は
  // 既定値で返す）。出典 scheduler.js の knownIds が「メモリのみ」なのと同じ。
  // --------------------------------------------------------------------------

  // 前回同期時点で存在した ID の集合（昇順ソート済みのハッシュ）。
  // syncSchedule() が「どれが新着か」を判定するのに使う。
  //
  // ★なぜ ID そのものではなくハッシュなのか:
  //   数千件のstd::stringは容量が大きい。ハッシュなら4バイト/件で済む。
  //   衝突すると「新着なのに新着でないと判定される」が、その写真は shown に
  //   無いので次ラウンドに PRI_NEVER で最優先選出される。これは
  //   NEW_INSERT_WINDOW を超えた新着に対して出典 scheduler.js が
  //   もともと行っている扱いと同じであり、劣化のしかたが安全側である。
  std::vector<std::uint32_t> knownIdHashes;

  // false = 未初期化（起動直後）。出典 scheduler.js の knownIds === null。
  // ★初回の syncSchedule() は「現 manifest を既知集合として記録するだけ」で
  //   何も差し込まない。停止中に増えた写真は shown に無いので、
  //   次ラウンドに PRI_NEVER で自然に上位選出される。
  bool knownIdsPrimed{false};
};

// ----------------------------------------------------------------------------
// 上限 ― これが「後付けできる形」の本体
// ----------------------------------------------------------------------------
//
// 0 = 無制限。
// Mac の既定は無制限でよいが、★Mac でも一度は上限付きでテストすること。
// 上限を掛けたときにスケジューラが壊れないことを Mac 上で確認できなければ、
// この仕組みは無いのと同じである。
struct SnapshotLimits {
  std::size_t maxShownEntries{0};
  std::size_t maxQueueEntries{0};

  // 直列化後の総バイト数の目安。IStateStore::capacity() から導くこと。
  std::size_t maxTotalBytes{0};
};

// Tab5 向けの暫定上限（NVS 単独で運転する縮退モード）。
//
// ★NVS の実使用量（hogo-meter の 4 namespace を引いた残り）は依然 **未実測**。
//   ただし 256 という数字は、もはや根拠が無いわけではない:
//   maxTotalBytes 4096 に対し、この形式は shown 1 件 ≈ 10 バイト
//   （"4:1001:27\n"）なので 256 件 = 約 2.6KB、queue 64 件 = 約 450 バイト、
//   ヘッダとシグネチャで 100 バイト弱。合計 3.1KB で 4096 に収まる。
//   すなわち「4KB に収まる件数」から逆算した値である。
//
// ★この上限では全網羅の周期が約 5.7 倍になる（ヘッダ冒頭の「決定 3」）。
//   設計値2000件を保持したいならNVSではないIStateStoreを使うこと。
inline constexpr SnapshotLimits kTab5ProvisionalLimits{
    /*maxShownEntries=*/256,
    /*maxQueueEntries=*/64,
    /*maxTotalBytes=*/4096,
};

// Mac（ファイル保存）向けの既定上限。
// ★「無制限」(=0) にしないのは、無制限だと Tab5 との差が Mac 上のテストで
//   一切見えなくなるため（state_store.hpp の StoreCapacity と同じ理由）。
//   設計値2000件に対して十分な余裕を取りつつ、上限機構は常に働かせる。
inline constexpr SnapshotLimits kMacDefaultLimits{
    /*maxShownEntries=*/8192,
    /*maxQueueEntries=*/4096,
    /*maxTotalBytes=*/256 * 1024,
};

// 上限に収まるよう切り詰める。
//
// 捨てる規則:
//   * shown      … round が最も古いものから捨てる（選択肢 A）。
//                  同じ round の中では photoId の昇順で先に捨てる
//                  （★同点の扱いを決めておかないと Mac と Tab5 で
//                    切り捨てられる写真が食い違い、再現性が崩れる）。
//   * playQueue  … **末尾** から捨てる。先頭が「次に出る写真」なので、
//                  先頭を捨てると再生位置が飛ぶ。
//   * maxTotalBytes … encodeSnapshot() の結果でしか測れないので、
//                  「切って符号化して測る」を繰り返す。★反復回数に上限を設ける
//                  （Tab5 で無限ループさせない）。
//
// limits の各値が 0 なら、その項目は無制限。
[[nodiscard]] SchedulerSnapshot truncateForStore(SchedulerSnapshot snapshot,
                                                 const SnapshotLimits& limits);

// ----------------------------------------------------------------------------
// 直列化 ― ★形式は未決定。1B が決める
// ----------------------------------------------------------------------------

[[nodiscard]] std::string encodeSnapshot(const SchedulerSnapshot& snapshot);

// 壊れた入力・未知のバージョンでは nullopt を返すこと。
// ★例外を投げないこと（Core の規律。docs/PORTABILITY.md）。
//   nullopt を受け取った側は「初回起動と同じ扱い」にすること。
[[nodiscard]] std::optional<SchedulerSnapshot> decodeSnapshot(std::string_view encoded);

// 永続化に使うキー。
// ★NVS のキー長上限は 15 文字（constants::kNvsMaxKeyBytes）。
//   旧実装の 'geoframe.play.v1' は 16 文字あり **Tab5 では通らない**。
inline constexpr std::string_view kSnapshotKey = "gf.play.v1";
static_assert(kSnapshotKey.size() <= 15, "NVS のキー長上限（15 文字）を超えている");

}  // namespace ambient::core
